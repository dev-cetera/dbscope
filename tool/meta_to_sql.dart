// Turns a dbscope metadata file (YAML/JSON, includes resolved) into SQL
// that creates the metadata tables and loads the file into them — the same
// DDL and upserts dbscope's "Initialize metadata tables…" and "Import
// metadata file into tables…" run, so a project can keep its metadata in
// the repo and push it to any environment with psql.
//
//   fvm dart run tool/meta_to_sql.dart path/to/meta.yaml \
//       [--schema dbscope] [--sqlite] [--prefix _dbscope_] [--replace]
//       [--out file.sql]
//
// --replace empties the four tables first, so the database ends up holding
// exactly the file (the repo is the source of truth). Without it, rows not
// in the file are kept.
//
// Output is one transaction, on stdout or in --out (prefer --out: `dart
// run` may print build-hook progress to stdout). Problems in the file go to stderr;
// any problem exits 1 without printing SQL, so a typo never half-loads.

import 'dart:io';

import 'package:dbscope/db/executor.dart';
import 'package:dbscope/db/sqlite_kind.dart';
import 'package:dbscope/meta/action_binding.dart';
import 'package:dbscope/meta/meta_index.dart';
import 'package:dbscope/meta/meta_models.dart';
import 'package:dbscope/meta/meta_settings.dart';
import 'package:dbscope/meta/meta_sources.dart';
import 'package:dbscope/meta/meta_writer.dart';
import 'package:dbscope/query/cancel_token.dart';
import 'package:dbscope/util/sql_quote.dart';

/// Records statements instead of running them, inlining parameters as
/// literals (quoteLiteral) so the output is plain SQL for psql/sqlite3.
class _SqlRecorder implements DbExecutor {
  _SqlRecorder({required this.sqlite});
  final bool sqlite;
  final List<String> statements = [];

  @override
  String get kind => sqlite ? kSqliteKind : 'postgres';

  @override
  bool get isOpen => true;

  @override
  DbCapabilities get capabilities => DbCapabilities.postgres;

  @override
  Future<DbResult> execute(
    String sql, {
    List<Object?>? positional,
    Map<String, Object?>? named,
    CancelToken? cancelToken,
  }) async {
    var text = sql;
    if (named != null && named.isNotEmpty) {
      final positional = toPositional(BoundSql(sql, named, const []));
      // One pass over the template, so a `$1` inside an inlined value is
      // never rewritten again.
      text = positional.sql.replaceAllMapped(
        RegExp(r'\$(\d+)'),
        (m) => quoteLiteral(positional.params[int.parse(m.group(1)!) - 1]),
      );
    }
    statements.add(text.trim().endsWith(';') ? text.trim() : '${text.trim()};');
    return const DbResult(columns: [], rows: []);
  }

  @override
  Future<void> setReadOnly(bool readOnly) async {}

  @override
  Future<void> close({bool force = false}) async {}
}

Future<void> main(List<String> args) async {
  String? path;
  var schema = kDefaultMetaSchema;
  var prefix = kDefaultMetaTablePrefix;
  var sqlite = false;
  var replace = false;
  String? outPath;
  String valueAfter(int i) {
    if (i + 1 >= args.length) {
      stderr.writeln('${args[i]} needs a value.');
      exit(64);
    }
    return args[i + 1];
  }

  for (var i = 0; i < args.length; i++) {
    switch (args[i]) {
      case '--schema':
        schema = valueAfter(i++);
      case '--prefix':
        prefix = valueAfter(i++);
      case '--sqlite':
        sqlite = true;
      case '--replace':
        replace = true;
      case '--out':
        outPath = valueAfter(i++);
      default:
        path = args[i];
    }
  }
  if (path == null) {
    stderr.writeln(
      'usage: dart run tool/meta_to_sql.dart <file> '
      '[--schema dbscope] [--sqlite] [--prefix _dbscope_] [--replace]',
    );
    exit(64);
  }

  final data = await FileSource.load(path);
  // Parse problems and kind-level problems (a chart without a type, an
  // action without run, …) both block the load.
  final problems = [
    ...data.problems,
    ...MetaIndex.build(mergeMetaSources([data])).problems,
  ];
  if (problems.isNotEmpty) {
    for (final p in problems) {
      stderr.writeln(p);
    }
    exit(1);
  }

  final settings = MetadataSettings(
    tablesMode: MetaTablesMode.custom,
    customName: sqlite ? prefix : schema,
  );
  final recorder = _SqlRecorder(sqlite: sqlite);
  final writer = MetaWriter(recorder, settings);
  final names = MetaTableNames.forExecutor(recorder, settings);

  final out = StringBuffer()
    ..writeln('-- Generated by dbscope tool/meta_to_sql.dart from $path')
    ..writeln('BEGIN;');
  if (!sqlite) {
    // Literals are inlined with standard quoting ('' doubling); make sure
    // backslashes mean nothing whatever the server default is.
    out.writeln('SET LOCAL standard_conforming_strings = on;');
  }
  for (final statement in splitStatements(writer.createTablesSql())) {
    out.writeln('$statement;');
  }
  if (replace) {
    // Children first (foreign keys).
    out
      ..writeln('DELETE FROM ${names.grants};')
      ..writeln('DELETE FROM ${names.members};')
      ..writeln('DELETE FROM ${names.roles};')
      ..writeln("DELETE FROM ${names.meta} WHERE id <> 'format';");
  }
  if (sqlite) {
    // createTables() seeds this for SQLite; the script path must too.
    out.writeln(
      'INSERT OR IGNORE INTO ${names.meta} (id, target, kind, spec) '
      "VALUES ('format', '*', 'format', '{\"version\": 1}');",
    );
  }
  await writer.importSource(data);
  for (final s in recorder.statements) {
    out.writeln(s);
  }
  out.writeln('COMMIT;');
  if (outPath == null) {
    stdout.write(out);
  } else {
    File(outPath).writeAsStringSync(out.toString());
  }
  stderr.writeln(
    'meta_to_sql: ${data.rows.length} rows, ${data.roles.length} roles, '
    '${data.members.length} members, ${data.grants.length} grants.',
  );
}
