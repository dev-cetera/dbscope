// What the database itself says about a table or column, read live from the
// catalog when the user opens "About …". Schema metadata is an extra layer
// on top; this is the native layer every database has:
//
//   Postgres: type (+ enum values and the type's COMMENT), nullability,
//   default, generated expression, identity, every constraint touching the
//   column (definition + COMMENT), every index touching it (definition +
//   COMMENT), and for tables: COMMENT, kind, owner, size, row estimate,
//   triggers (+ COMMENT), policies (RLS).
//   SQLite: type, nullability, default, primary key, indexes, the CREATE
//   statement.
//
// Read on demand (one dialog = a few catalog queries), never cached: it is
// cheap and always current.

import '../db/executor.dart';
import 'meta_sources.dart';

class NativeFact {
  const NativeFact(this.label, this.detail, {this.comment});

  /// Short heading, e.g. "check_items_name" or "default".
  final String label;

  /// The definition or value, e.g. `CHECK (char_length(name) <= 80)`.
  final String detail;

  /// COMMENT ON the object, when there is one.
  final String? comment;
}

class NativeFacts {
  const NativeFacts({
    this.comment,
    this.attributes = const [],
    this.constraints = const [],
    this.indexes = const [],
    this.triggers = const [],
    this.policies = const [],
  });
  final String? comment;
  final List<NativeFact> attributes;
  final List<NativeFact> constraints;
  final List<NativeFact> indexes;
  final List<NativeFact> triggers;
  final List<NativeFact> policies;

  bool get isEmpty =>
      comment == null &&
      attributes.isEmpty &&
      constraints.isEmpty &&
      indexes.isEmpty &&
      triggers.isEmpty &&
      policies.isEmpty;
}

String? _text(Object? value) {
  if (value == null) return null;
  final text = value.toString().trim();
  return text.isEmpty ? null : text;
}

Future<NativeFacts> loadColumnFacts(
  DbExecutor executor, {
  required String schema,
  required String table,
  required String column,
}) {
  if (isSqliteExecutor(executor)) {
    return _sqliteColumnFacts(executor, table, column);
  }
  return _postgresColumnFacts(executor, schema, table, column);
}

Future<NativeFacts> loadTableFacts(
  DbExecutor executor, {
  required String schema,
  required String table,
}) {
  if (isSqliteExecutor(executor)) return _sqliteTableFacts(executor, table);
  return _postgresTableFacts(executor, schema, table);
}

Future<NativeFacts> _postgresColumnFacts(
  DbExecutor executor,
  String schema,
  String table,
  String column,
) async {
  final named = {'schema': schema, 'table': table, 'column': column};
  final columnResult = await executor.execute('''
 SELECT
 col_description(c.oid, a.attnum) AS comment,
 format_type(a.atttypid, a.atttypmod) AS type,
 a.attnotnull,
 pg_get_expr(d.adbin, d.adrelid) AS default_expr,
 a.attgenerated::text,
 a.attidentity::text,
 obj_description(t.oid, 'pg_type') AS type_comment,
 (SELECT string_agg(e.enumlabel, ', ' ORDER BY e.enumsortorder)
 FROM pg_enum e WHERE e.enumtypid = t.oid) AS enum_values,
 t.typname::text
 FROM pg_attribute a
 JOIN pg_class c ON c.oid = a.attrelid
 JOIN pg_namespace n ON n.oid = c.relnamespace
 JOIN pg_type t ON t.oid = a.atttypid
 LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
 WHERE n.nspname = @schema AND c.relname = @table AND a.attname = @column
 AND NOT a.attisdropped
 ''', named: named);
  if (columnResult.isEmpty) return const NativeFacts();
  final row = columnResult.first;
  final generated = _text(row[4]);
  final identity = _text(row[5]);
  final attributes = <NativeFact>[
    NativeFact('type', row[1].toString(), comment: _text(row[6])),
    NativeFact('nullable', row[2] == true ? 'NOT NULL' : 'nullable'),
    if (_text(row[3]) != null)
      NativeFact(
        generated == 's' ? 'generated (stored)' : 'default',
        _text(row[3])!,
      ),
    if (identity != null)
      NativeFact(
        'identity',
        identity == 'a' ? 'GENERATED ALWAYS' : 'GENERATED BY DEFAULT',
      ),
    if (_text(row[7]) != null) NativeFact('enum ${row[8]}', _text(row[7])!, comment: _text(row[6])),
  ];

  final constraintResult = await executor.execute('''
 SELECT con.conname::text, pg_get_constraintdef(con.oid, true),
 obj_description(con.oid, 'pg_constraint')
 FROM pg_constraint con
 JOIN pg_class c ON c.oid = con.conrelid
 JOIN pg_namespace n ON n.oid = c.relnamespace
 JOIN pg_attribute a ON a.attrelid = c.oid AND a.attname = @column
 WHERE n.nspname = @schema AND c.relname = @table
 AND a.attnum = ANY(con.conkey)
 ORDER BY con.contype, con.conname
 ''', named: named);

  final indexResult = await executor.execute('''
 SELECT i.relname::text, pg_get_indexdef(i.oid),
 obj_description(i.oid, 'pg_class')
 FROM pg_index x
 JOIN pg_class i ON i.oid = x.indexrelid
 JOIN pg_class c ON c.oid = x.indrelid
 JOIN pg_namespace n ON n.oid = c.relnamespace
 JOIN pg_attribute a ON a.attrelid = c.oid AND a.attname = @column
 WHERE n.nspname = @schema AND c.relname = @table
 AND (a.attnum = ANY(x.indkey)
 OR pg_get_expr(x.indexprs, x.indrelid) LIKE '%' || @column || '%'
 OR pg_get_expr(x.indpred, x.indrelid) LIKE '%' || @column || '%')
 ORDER BY i.relname
 ''', named: named);

  return NativeFacts(
    comment: _text(row[0]),
    attributes: attributes,
    constraints: [
      for (final factRow in constraintResult.rows)
        NativeFact(
          factRow[0].toString(),
          factRow[1].toString(),
          comment: _text(factRow[2]),
        ),
    ],
    indexes: [
      for (final factRow in indexResult.rows)
        NativeFact(
          factRow[0].toString(),
          factRow[1].toString(),
          comment: _text(factRow[2]),
        ),
    ],
  );
}

Future<NativeFacts> _postgresTableFacts(
  DbExecutor executor,
  String schema,
  String table,
) async {
  final named = {'schema': schema, 'table': table};
  final tableResult = await executor.execute('''
 SELECT obj_description(c.oid, 'pg_class'),
 CASE c.relkind WHEN 'r' THEN 'table' WHEN 'p' THEN 'partitioned table'
 WHEN 'v' THEN 'view' WHEN 'm' THEN 'materialized view'
 WHEN 'f' THEN 'foreign table' ELSE c.relkind::text END,
 pg_get_userbyid(c.relowner)::text,
 pg_size_pretty(pg_total_relation_size(c.oid)),
 c.reltuples::bigint,
 c.relrowsecurity,
 obj_description(n.oid, 'pg_namespace'),
 CASE WHEN c.relkind IN ('v', 'm') THEN pg_get_viewdef(c.oid, true) END
 FROM pg_class c
 JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = @schema AND c.relname = @table
 ''', named: named);
  if (tableResult.isEmpty) return const NativeFacts();
  final row = tableResult.first;
  final attributes = <NativeFact>[
    NativeFact('kind', row[1].toString()),
    NativeFact('owner', row[2].toString()),
    NativeFact('size (with indexes)', row[3].toString()),
    NativeFact('estimated rows', row[4].toString()),
    NativeFact('row-level security', row[5] == true ? 'enabled' : 'off'),
    if (_text(row[6]) != null) NativeFact('schema $schema', '', comment: _text(row[6])),
    if (_text(row[7]) != null) NativeFact('definition', _text(row[7])!),
  ];
  final constraintResult = await executor.execute('''
 SELECT con.conname::text, pg_get_constraintdef(con.oid, true),
 obj_description(con.oid, 'pg_constraint')
 FROM pg_constraint con
 JOIN pg_class c ON c.oid = con.conrelid
 JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = @schema AND c.relname = @table
 ORDER BY con.contype, con.conname
 ''', named: named);
  final indexResult = await executor.execute('''
 SELECT i.relname::text, pg_get_indexdef(i.oid),
 obj_description(i.oid, 'pg_class')
 FROM pg_index x
 JOIN pg_class i ON i.oid = x.indexrelid
 JOIN pg_class c ON c.oid = x.indrelid
 JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = @schema AND c.relname = @table
 ORDER BY i.relname
 ''', named: named);
  final triggerResult = await executor.execute('''
 SELECT t.tgname::text, pg_get_triggerdef(t.oid, true),
 obj_description(t.oid, 'pg_trigger')
 FROM pg_trigger t
 JOIN pg_class c ON c.oid = t.tgrelid
 JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = @schema AND c.relname = @table AND NOT t.tgisinternal
 ORDER BY t.tgname
 ''', named: named);
  final policyResult = await executor.execute('''
 SELECT p.polname::text,
 'FOR ' || CASE p.polcmd WHEN 'r' THEN 'SELECT' WHEN 'a' THEN 'INSERT'
 WHEN 'w' THEN 'UPDATE' WHEN 'd' THEN 'DELETE' ELSE 'ALL' END
 || COALESCE(' USING (' || pg_get_expr(p.polqual, p.polrelid) || ')', '')
 || COALESCE(' WITH CHECK (' || pg_get_expr(p.polwithcheck, p.polrelid) || ')', ''),
 obj_description(p.oid, 'pg_policy')
 FROM pg_policy p
 JOIN pg_class c ON c.oid = p.polrelid
 JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = @schema AND c.relname = @table
 ORDER BY p.polname
 ''', named: named);
  List<NativeFact> facts(DbResult result) => [
    for (final factRow in result.rows)
      NativeFact(
        factRow[0].toString(),
        factRow[1].toString(),
        comment: _text(factRow[2]),
      ),
  ];
  return NativeFacts(
    comment: _text(row[0]),
    attributes: attributes,
    constraints: facts(constraintResult),
    indexes: facts(indexResult),
    triggers: facts(triggerResult),
    policies: facts(policyResult),
  );
}

Future<NativeFacts> _sqliteColumnFacts(
  DbExecutor executor,
  String table,
  String column,
) async {
  final info = await executor.execute(
    'SELECT type, "notnull", dflt_value, pk FROM pragma_table_info(?1) '
    'WHERE name = ?2',
    positional: [table, column],
  );
  if (info.isEmpty) return const NativeFacts();
  final row = info.first;
  final indexes = <NativeFact>[];
  final list = await executor.execute(
    'SELECT name, "unique" FROM pragma_index_list(?1)',
    positional: [table],
  );
  for (final index in list.rows) {
    final indexColumns = await executor.execute(
      'SELECT name FROM pragma_index_info(?1)',
      positional: [index[0]],
    );
    final names = [
      for (final columnRow in indexColumns.rows) columnRow[0].toString(),
    ];
    if (!names.contains(column)) continue;
    indexes.add(
      NativeFact(
        index[0].toString(),
        '${'${index[1]}' == '1' ? 'UNIQUE ' : ''}(${names.join(', ')})',
      ),
    );
  }
  return NativeFacts(
    attributes: [
      NativeFact('type', _text(row[0]) ?? '(none)'),
      NativeFact('nullable', '${row[1]}' == '1' ? 'NOT NULL' : 'nullable'),
      if (_text(row[2]) != null) NativeFact('default', _text(row[2])!),
      if ('${row[3]}' != '0') NativeFact('primary key', 'position ${row[3]}'),
    ],
    indexes: indexes,
  );
}

Future<NativeFacts> _sqliteTableFacts(DbExecutor executor, String table) async {
  final result = await executor.execute(
    "SELECT type, sql FROM sqlite_master WHERE name = ?1 AND type IN ('table', 'view')",
    positional: [table],
  );
  if (result.isEmpty) return const NativeFacts();
  final indexResult = await executor.execute(
    "SELECT name, sql FROM sqlite_master WHERE type = 'index' AND tbl_name = ?1",
    positional: [table],
  );
  final triggerResult = await executor.execute(
    "SELECT name, sql FROM sqlite_master WHERE type = 'trigger' AND tbl_name = ?1",
    positional: [table],
  );
  return NativeFacts(
    attributes: [
      NativeFact('kind', result.first[0].toString()),
      if (_text(result.first[1]) != null) NativeFact('definition', _text(result.first[1])!),
    ],
    indexes: [
      for (final indexRow in indexResult.rows)
        NativeFact(indexRow[0].toString(), _text(indexRow[1]) ?? '(automatic)'),
    ],
    triggers: [
      for (final triggerRow in triggerResult.rows)
        NativeFact(triggerRow[0].toString(), _text(triggerRow[1]) ?? ''),
    ],
  );
}
