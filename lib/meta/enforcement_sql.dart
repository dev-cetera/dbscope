// Turns access-control grants into real Postgres privileges (plan.md
// "Enforced"). Pure: the caller supplies the catalog; this returns SQL for
// review — dbscope never runs it on its own — plus the privileges the SQL
// should leave in place, so a later check can report drift.
//
// Postgres limits it respects:
// - no native masking: `masked` becomes "no SELECT on that column";
// - a column REVOKE does nothing while the role holds table-level SELECT,
//   so a table with any hidden column gets per-column SELECT instead;
//   columns added by later migrations are then invisible to the role until
//   this is regenerated (the drift check flags exactly that);
// - a table's owner bypasses privileges — enforcement only binds logins
//   that do not own the tables.

import '../util/sql_quote.dart';
import 'access_policy.dart';
import 'meta_models.dart';

class EnforcementTable {
  const EnforcementTable({
    required this.schema,
    required this.table,
    required this.columns,
    this.primaryKey = const [],
    this.isView = false,
  });
  final String schema;
  final String table;
  final List<String> columns;
  final List<String> primaryKey;

  /// Views (and materialized views) get SELECT only.
  final bool isView;
}

enum Privilege { select, insert, update, delete }

/// One privilege the generated SQL leaves in place (or removes).
class PrivilegeExpectation {
  const PrivilegeExpectation({
    required this.dbRole,
    required this.schema,
    required this.table,
    this.column,
    required this.privilege,
    required this.granted,
  });
  final String dbRole;
  final String schema;
  final String table;

  /// Null for a table-level privilege.
  final String? column;
  final Privilege privilege;
  final bool granted;

  String get describe =>
      '$dbRole ${granted ? 'should' : 'should not'} have '
      '${privilege.name.toUpperCase()} on $schema.$table'
      '${column == null ? '' : '($column)'}';
}

class EnforcementPlan {
  const EnforcementPlan({
    required this.statements,
    required this.expectations,
    required this.notes,
  });
  final List<String> statements;
  final List<PrivilegeExpectation> expectations;

  /// Roles skipped (no db_role) and other notes for the reviewer.
  final List<String> notes;

  String get script => statements.join('\n');
}

EnforcementPlan buildEnforcementPlan({
  required MetaDocument document,
  required RbacSettings settings,
  required List<EnforcementTable> tables,
  bool Function(String schema, String table)? isMetaTable,
  List<({String schema, String table})> metaTables = const [],
}) {
  final statements = <String>[
    '-- Generated by dbscope from the access-control grants.',
    '-- Review before running. Run as a role that can GRANT on these tables.',
    '-- masked is not expressible in Postgres: masked columns get no SELECT.',
    '',
  ];
  final expectations = <PrivilegeExpectation>[];
  final notes = <String>[];
  // Several dbscope roles may map to one Postgres role: a login holding
  // that role holds all of them, so they resolve together (the union),
  // and the role gets ONE block — separate blocks would each start with a
  // REVOKE and clobber the previous one's grants.
  final rolesByDbRole = <String, List<String>>{};
  for (final role in document.roles) {
    final dbRole = role.dbRole;
    if (dbRole == null) {
      notes.add(
        'Role "${role.id}" has no db_role, so it gets no Postgres '
        'privileges (guardrails only).',
      );
      continue;
    }
    (rolesByDbRole[dbRole] ??= []).add(role.id);
  }

  final dbRoles = rolesByDbRole.keys.toList()..sort();
  for (final dbRole in dbRoles) {
    final roleIds = rolesByDbRole[dbRole]!;
    final quotedRole = quoteIdent(dbRole);
    final policy = AccessPolicy.resolve(
      document: document,
      settings: settings,
      identity: AccessIdentity.anonymous,
      viewAsRoleIds: roleIds.toSet(),
    );
    statements.add('-- ${roleIds.join(', ')} → $dbRole');
    final usageSchemas = <String>{};
    final insertSchemas = <String>{};
    for (final enforcementTable in tables) {
      if (isMetaTable?.call(enforcementTable.schema, enforcementTable.table) ?? false) {
        continue;
      }
      final qualified = quoteQualified(
        enforcementTable.schema,
        enforcementTable.table,
      );
      // Per object (tables AND views), so nothing outside this plan's list
      // is revoked and every listed relation is re-granted below.
      statements.add('REVOKE ALL ON $qualified FROM $quotedRole;');
      final tableLevel = policy.forTable(enforcementTable.schema, enforcementTable.table).level;
      void expect(
        Privilege privilege, {
        required bool granted,
        String? column,
      }) => expectations.add(
        PrivilegeExpectation(
          dbRole: dbRole,
          schema: enforcementTable.schema,
          table: enforcementTable.table,
          column: column,
          privilege: privilege,
          granted: granted,
        ),
      );

      if (tableLevel == AccessLevel.none) {
        expect(Privilege.select, granted: false);
        continue;
      }
      final readable = <String>[];
      final editable = <String>[];
      for (final column in enforcementTable.columns) {
        final level = policy
            .forColumn(
              enforcementTable.schema,
              enforcementTable.table,
              column,
              isPrimaryKey: enforcementTable.primaryKey.contains(column),
            )
            .level;
        // Primary keys floor at masked in dbscope (paging needs them); in
        // Postgres the login must SELECT them for anything to work.
        final isPrimaryKey = enforcementTable.primaryKey.contains(column);
        if (level.atLeast(AccessLevel.read) || isPrimaryKey) {
          readable.add(column);
        }
        if (!enforcementTable.isView &&
            level.atLeast(AccessLevel.edit) &&
            tableLevel.atLeast(AccessLevel.edit)) {
          editable.add(column);
        }
      }
      if (readable.isEmpty) {
        expect(Privilege.select, granted: false);
        continue;
      }
      usageSchemas.add(enforcementTable.schema);
      final allReadable = readable.length == enforcementTable.columns.length;
      if (allReadable) {
        statements.add('GRANT SELECT ON $qualified TO $quotedRole;');
        expect(Privilege.select, granted: true);
      } else {
        final columnList = readable.map(quoteIdent).join(', ');
        statements.add(
          'GRANT SELECT ($columnList) ON $qualified TO $quotedRole;',
        );
        expect(Privilege.select, granted: false);
        for (final column in enforcementTable.columns) {
          expect(
            Privilege.select,
            granted: readable.contains(column),
            column: column,
          );
        }
      }
      if (enforcementTable.isView) continue;
      if (editable.isNotEmpty) {
        if (editable.length == enforcementTable.columns.length) {
          statements.add('GRANT UPDATE ON $qualified TO $quotedRole;');
          expect(Privilege.update, granted: true);
        } else {
          final columnList = editable.map(quoteIdent).join(', ');
          statements.add(
            'GRANT UPDATE ($columnList) ON $qualified TO $quotedRole;',
          );
          for (final column in enforcementTable.columns) {
            expect(
              Privilege.update,
              granted: editable.contains(column),
              column: column,
            );
          }
        }
      } else {
        expect(Privilege.update, granted: false);
      }
      final full = tableLevel.atLeast(AccessLevel.full);
      if (full) {
        statements.add('GRANT INSERT, DELETE ON $qualified TO $quotedRole;');
        insertSchemas.add(enforcementTable.schema);
      }
      expect(Privilege.insert, granted: full);
      expect(Privilege.delete, granted: full);
    }
    for (final schema in usageSchemas.toList()..sort()) {
      statements.add(
        'GRANT USAGE ON SCHEMA ${quoteIdent(schema)} TO $quotedRole;',
      );
    }
    // INSERT into a serial/identity table needs the sequence too.
    for (final schema in insertSchemas.toList()..sort()) {
      statements.add(
        'GRANT USAGE ON ALL SEQUENCES IN SCHEMA ${quoteIdent(schema)} '
        'TO $quotedRole;',
      );
    }
    if (metaTables.isNotEmpty) {
      final canManage = policy.can(Capability.manage);
      final metaSchemas = {
        for (final metaTable in metaTables) metaTable.schema,
      };
      for (final schema in metaSchemas) {
        statements.add(
          'GRANT USAGE ON SCHEMA ${quoteIdent(schema)} TO $quotedRole;',
        );
      }
      for (final metaTable in metaTables) {
        final qualifiedMetaTable = quoteQualified(
          metaTable.schema,
          metaTable.table,
        );
        statements.add(
          canManage
              ? 'GRANT SELECT, INSERT, UPDATE, DELETE ON $qualifiedMetaTable '
                    'TO $quotedRole;'
              : 'GRANT SELECT ON $qualifiedMetaTable TO $quotedRole;',
        );
      }
    }
    statements.add('');
  }
  if (document.roles.every((role) => role.dbRole == null)) {
    notes.add(
      'No role has a db_role, so there is nothing to enforce in '
      'Postgres yet.',
    );
  }
  return EnforcementPlan(
    statements: statements,
    expectations: expectations,
    notes: notes,
  );
}
